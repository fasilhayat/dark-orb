namespace BattleArena.Application.Services;

using Core.Entities;
using Interfaces;
using Models;

// XP rewards and level-up logic for combats.
// XP is awarded to each surviving party member after a combat based on:
//   - base value from enemy levels (difficulty)
//   - bonus per critical hit landed by the party
//   - penalty per fumble by the party
//   - round factor: fights that are very quick (efficient) or very long (grueling)
//     earn a multiplier bonus; standard-length fights earn base XP.
// Level thresholds, strike rating bonuses, and accessory slot unlocks are defined in LevelProgression.
public class LevelingService
{
    private readonly IDiceService _dice;

    public LevelingService(IDiceService dice)
    {
        _dice = dice;
    }

    private const int XpMultiplier = 12;
    private const int CritBonus = 8;
    private const int FumblePenalty = 8;
    private const double RoundFactorK = 0.3;
    private const double RoundFactorMin = 0.5;
    private const double RoundFactorMax = 2.0;

    // Returns the total XP pool generated by a combat, factoring in difficulty,
    // critical hits, fumbles, and combat duration.
    public int ComputeCombatXp(
        IEnumerable<Character> party,
        IEnumerable<Character> enemies,
        IReadOnlyCollection<CombatLogEntry> log,
        int totalTicks)
    {
        var enemyList = enemies.ToList();
        var baseXp = enemyList.Sum(e => e.Level) * XpMultiplier;
        var partyNames = party.Select(c => c.Name).ToHashSet();

        var partyCrits = log.Count(e =>
            e.EventType == "Attack" && e.IsCritical == true && partyNames.Contains(e.ActorName));
        var partyFumbles = log.Count(e =>
            e.EventType == "Attack" && e.IsFumble == true && partyNames.Contains(e.ActorName));

        var expectedRounds = Math.Max(1, (party.Count() + enemyList.Count) * 2);
        var ratio = (double)totalTicks / expectedRounds;
        var roundFactor = 1.0 + Math.Abs(ratio - 1.0) * RoundFactorK;
        roundFactor = Math.Clamp(roundFactor, RoundFactorMin, RoundFactorMax);

        var totalXp = (int)(baseXp * roundFactor) + (partyCrits - partyFumbles) * CritBonus;
        var minimumXp = enemyList.Sum(e => e.Level);
        return Math.Max(minimumXp, totalXp);
    }

    // Splits XP among survivors (rounds down). Dead/KO'd members get nothing.
    public IReadOnlyDictionary<string, int> AwardCombatXp(
        IEnumerable<Character> party,
        IEnumerable<Character> enemies,
        IReadOnlyCollection<CombatLogEntry> log,
        int totalTicks)
    {
        var totalXp = ComputeCombatXp(party, enemies, log, totalTicks);
        var survivors = party.Where(c => c.IsAlive).ToList();
        if (survivors.Count == 0)
            return new Dictionary<string, int>();

        var share = totalXp / survivors.Count;
        var result = new Dictionary<string, int>();
        foreach (var c in survivors)
        {
            var oldLevel = c.Level;
            c.ExperiencePoints += share;
            c.Level = LevelProgression.LevelFromXp(c.ExperiencePoints);
            if (c.Level > oldLevel)
            {
                var staminaMod = (c.Stamina - 10) / 2;
                var hitDieSides = LevelProgression.HitDieSides(c.ClassId);
                var raceHpBonus = c.Race?.HitPointBonus ?? 0;
                for (var lvl = oldLevel; lvl < c.Level; lvl++)
                {
                    var rolled = _dice.Roll(LevelProgression.HitDieToDieType(hitDieSides));
                    var gain = Math.Max(1, rolled + staminaMod + raceHpBonus);
                    c.MaxHitPoints += gain;
                    c.CurrentHitPoints += gain;
                }
            }
            result[c.Name] = share;
        }
        return result;
    }

    // Effective strike rating after level-based reductions.
    public int EffectiveStrikeRating(Character character)
    {
        var archetype = LevelProgression.Archetype(character.ClassId);
        var bonus = LevelProgression.SrBonus(character.Level, archetype);
        return Math.Max(1, character.StrikeRating - bonus);
    }

    // Number of accessory slots available at the character's current level and class.
    public int AccessorySlotCount(Character character)
    {
        var archetype = LevelProgression.Archetype(character.ClassId);
        return LevelProgression.AccessorySlots(character.Level, archetype);
    }

    // Describes the level-up delta, if any.
    public LevelUpResult? CheckLevelUp(Character before, Character after)
    {
        if (after.Level <= before.Level) return null;
        return new LevelUpResult
        {
            OldLevel = before.Level,
            NewLevel = after.Level,
            StrikeRatingImproved = EffectiveStrikeRating(after) < EffectiveStrikeRating(before),
            NewAccessorySlots = AccessorySlotCount(after)
        };
    }
}

public class LevelUpResult
{
    public int OldLevel { get; init; }
    public int NewLevel { get; init; }
    public bool StrikeRatingImproved { get; init; }
    public int NewAccessorySlots { get; init; }
}
